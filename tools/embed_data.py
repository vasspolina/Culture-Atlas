#!/usr/bin/env python3
"""Rewrite assets/institutions.js, the institution data the page loads, from institutions.json (after tools/clean_data.py).

The records used to be embedded in index.html; they live in their own classic script now, so a new release of the
page does not make every phone re-download them. Bump the `?v=` on the assets/institutions.js tag in index.html after
running this, so browsers and the service worker pick up the new records."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'assets' / 'institutions.js'
data = json.load(open(ROOT / 'institutions.json', encoding='utf-8'))
OUT.write_text(
    '// The records of every space on the atlas. Generated by tools/embed_data.py from institutions.json; do not edit by hand.\n'
    "// Loaded as a classic script before the page's own, so `ALL_INSTITUTIONS` is in the shared global scope as before.\n"
    'const ALL_INSTITUTIONS = ' + json.dumps(data, ensure_ascii=True, separators=(',', ':')) + ';\n',
    encoding='utf-8')
print('wrote', OUT.relative_to(ROOT), 'with', len(data), 'records')
